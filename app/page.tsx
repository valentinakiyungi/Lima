'use client';

import React, { useState, useEffect, useRef } from 'react';

const API_BASE_URL = (process.env.NEXT_PUBLIC_API_URL || "https://lima-api-yypp.onrender.com").replace(/\/$/, "");
const REPO_URL = "https://github.com/valentinakiyungi/Lima";

// Safari records mp4, Chrome/Firefox record webm/ogg, so pick what the browser supports.
const AUDIO_TYPES: { mime: string; ext: string }[] = [
  { mime: "audio/webm;codecs=opus", ext: "webm" },
  { mime: "audio/webm", ext: "webm" },
  { mime: "audio/mp4", ext: "mp4" },
  { mime: "audio/ogg;codecs=opus", ext: "ogg" },
];

const GREETING = "Hello! I'm Lima. What can I help you with today?";

// Speak a line with the browser's built-in voice. Always resolves (even if speech is unsupported
// or never fires "end", e.g. on some mobile browsers) so recording is never blocked.
let currentUtterance: SpeechSynthesisUtterance | null = null; // keep a reference so browsers don't drop it mid-sentence

const speak = (text: string, lang = 'en-US'): Promise<void> =>
  new Promise((resolve) => {
    if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
      resolve();
      return;
    }
    const synth = window.speechSynthesis;
    // Only cancel speech that is really playing; cancel() right before speak() makes Chrome/Safari drop it.
    const wasBusy = synth.speaking || synth.pending;
    if (wasBusy) synth.cancel();

    const utterance = new SpeechSynthesisUtterance(text);
    utterance.lang = lang;
    const wanted = lang.toLowerCase().replace('_', '-');
    const voices = synth.getVoices();
    const voice =
      voices.find((v) => v.lang.toLowerCase().replace('_', '-') === wanted) ||
      voices.find((v) => v.lang.toLowerCase().startsWith(wanted.slice(0, 2)));
    if (voice) utterance.voice = voice;
    currentUtterance = utterance;

    const timer = setTimeout(() => resolve(), 9000);
    const done = () => {
      clearTimeout(timer);
      resolve();
    };
    utterance.onend = done;
    utterance.onerror = (e) => {
      console.warn('Speech error:', e.error);
      done();
    };
    const start = () => {
      synth.resume(); // Chrome can leave the queue paused after a cancel
      synth.speak(currentUtterance as SpeechSynthesisUtterance);
    };
    if (wasBusy) setTimeout(start, 120);
    else start();
  });

// ---- Lima's voice: generated by the backend so it sounds the same on every phone and computer ----
const SILENT_WAV = 'data:audio/wav;base64,UklGRiwAAABXQVZFZm10IBAAAAABAAEAQB8AAEAfAAABAAgAZGF0YQgAAACAgICAgICAgA==';
let audioEl: HTMLAudioElement | null = null;
let speechToken = 0;

const getAudio = (): HTMLAudioElement => {
  if (!audioEl) audioEl = new Audio();
  return audioEl;
};

// Phones only let a page play audio after a tap. Playing a silent clip during the tap unlocks
// this one audio element, so Lima's answer (which arrives later) can still be played.
const unlockAudio = () => {
  const a = getAudio();
  a.src = SILENT_WAV;
  a.play().catch(() => {});
};

const stopSpeaking = () => {
  speechToken++;
  if (audioEl) audioEl.pause();
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) window.speechSynthesis.cancel();
};

// Resolves true if the clip played to the end, false if the browser refused or it failed.
const playUrl = (url: string): Promise<boolean> =>
  new Promise((resolve) => {
    const a = getAudio();
    a.onended = () => resolve(true);
    a.onerror = () => resolve(false);
    a.src = url;
    a.play().catch(() => resolve(false));
  });

const fetchSpeech = async (text: string, lang: string): Promise<string | null> => {
  try {
    const body = new FormData();
    body.append('text', text);
    body.append('lang', lang);
    const res = await fetch(`${API_BASE_URL}/tts`, { method: 'POST', body });
    if (!res.ok) return null;
    return URL.createObjectURL(await res.blob());
  } catch {
    return null;
  }
};

// Speak with the server voice; fall back to the browser's own voice if that is not possible.
const speakSmart = async (text: string, lang: string) => {
  const token = ++speechToken;
  const url = await fetchSpeech(text, lang);
  if (token !== speechToken) return; // the user tapped again while the audio was loading
  if (url) {
    const played = await playUrl(url);
    URL.revokeObjectURL(url);
    if (played) return;
  }
  await speak(text, lang);
};

const iconButton =
  "w-11 h-11 shrink-0 inline-flex items-center justify-center active:scale-95 rounded-xl border-2 border-slate-600 dark:border-slate-500 bg-slate-100 dark:bg-slate-800 text-slate-800 dark:text-slate-200 hover:bg-slate-200 dark:hover:bg-slate-700 transition-colors";

export default function Home() {
  const [darkMode, setDarkMode] = useState(false);
  const [showInstructions, setShowInstructions] = useState(false);
  const [isRecording, setIsRecording] = useState(false);
  const [loading, setLoading] = useState(false);
  const [greeting, setGreeting] = useState(false);
  const [waitingMic, setWaitingMic] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<{
    transcript?: string;
    summary?: string;
    action_items?: string[];
    reply?: string;
    follow_up?: string;
    language?: string;
  } | null>(null);

  const mediaRecorderRef = useRef<MediaRecorder | null>(null);
  const audioChunksRef = useRef<Blob[]>([]);
  const historyRef = useRef<{ role: string; content: string }[]>([]);
  const greetingUrlRef = useRef<string | null>(null);
  const recordStartRef = useRef(0);

  useEffect(() => {
    document.documentElement.classList.toggle('dark', darkMode);
    let meta = document.querySelector('meta[name="theme-color"][data-lima]');
    if (!meta) {
      meta = document.createElement('meta');
      meta.setAttribute('name', 'theme-color');
      meta.setAttribute('data-lima', '');
      document.head.appendChild(meta);
    }
    meta.setAttribute('content', darkMode ? '#020617' : '#f1f5f9');
  }, [darkMode]);

  // Start in the phone's light/dark mode unless the user chose one before.
  useEffect(() => {
    let initial = window.matchMedia('(prefers-color-scheme: dark)').matches;
    try {
      const saved = localStorage.getItem('lima-theme');
      if (saved) initial = saved === 'dark';
    } catch {}
    setDarkMode(initial);
  }, []);

  const toggleTheme = () => {
    const next = !darkMode;
    setDarkMode(next);
    try {
      localStorage.setItem('lima-theme', next ? 'dark' : 'light');
    } catch {}
  };

  // The free Render backend sleeps when idle; ping it on load so it is awake when the user records.
  useEffect(() => {
    fetch(`${API_BASE_URL}/health`).catch(() => {});
    fetchSpeech(GREETING, 'en-US').then((url) => {
      greetingUrlRef.current = url;
    });
    if ('speechSynthesis' in window) window.speechSynthesis.getVoices(); // start loading voices early
  }, []);

  const startRecording = async () => {
    setError(null);
    audioChunksRef.current = [];
    try {
      // Browsers only allow speech that starts inside the tap, so the greeting starts right away.
      // The microphone is requested only AFTER it ends: phones lower or cut off speech while the
      // microphone is opening, so the two must not overlap.
      if (historyRef.current.length === 0) {
        setGreeting(true);
        const played = greetingUrlRef.current ? await playUrl(greetingUrlRef.current) : false;
        if (!played) await speak(GREETING);
        setGreeting(false);
      } else {
        stopSpeaking(); // stop Lima mid-answer when the user taps to talk again
      }
      setWaitingMic(true);
      const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
      setWaitingMic(false);
      const picked =
        typeof MediaRecorder !== 'undefined'
          ? AUDIO_TYPES.find((t) => MediaRecorder.isTypeSupported(t.mime))
          : undefined;
      const mediaRecorder = picked
        ? new MediaRecorder(stream, { mimeType: picked.mime })
        : new MediaRecorder(stream);
      mediaRecorderRef.current = mediaRecorder;

      mediaRecorder.ondataavailable = (event) => {
        if (event.data.size > 0) {
          audioChunksRef.current.push(event.data);
        }
      };

      mediaRecorder.onstop = async () => {
        const type = mediaRecorder.mimeType || picked?.mime || 'audio/webm';
        const ext = AUDIO_TYPES.find((t) => type.startsWith(t.mime.split(';')[0]))?.ext || 'webm';
        const audioBlob = new Blob(audioChunksRef.current, { type });
        if (Date.now() - recordStartRef.current < 1000 || audioBlob.size < 1500) {
          setError('That recording was too short. Tap the button, wait until it says "Stop & Send", speak for a few seconds, then tap again.');
          return;
        }
        await sendAudioToBackend(audioBlob, ext);
      };

      mediaRecorder.start();
      recordStartRef.current = Date.now();
      setIsRecording(true);
    } catch (err) {
      setGreeting(false);
      setWaitingMic(false);
      console.error("Microphone access error:", err);
      setError("Microphone access was denied or is not supported in this browser.");
    }
  };

  const stopRecording = () => {
    if (mediaRecorderRef.current) {
      mediaRecorderRef.current.stop();
      mediaRecorderRef.current.stream.getTracks().forEach((track) => track.stop());
    }
    setIsRecording(false);
  };

  const handleRecordClick = () => {
    unlockAudio();
    if (isRecording) {
      stopRecording();
    } else {
      startRecording();
    }
  };

  const listen = () => {
    if (!result?.reply) return;
    const spoken = [result.reply, result.follow_up].filter(Boolean).join(" ");
    void speakSmart(spoken, result.language || "en-US");
  };

  const sendAudioToBackend = async (audioBlob: Blob, ext: string) => {
    setLoading(true);
    setError(null);
    const formData = new FormData();
    formData.append("file", audioBlob, `voice_note.${ext}`);
    formData.append("user_id", "val_123");
    formData.append("timezone", Intl.DateTimeFormat().resolvedOptions().timeZone || "");
    formData.append("history", JSON.stringify(historyRef.current.slice(-6)));

    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 120000);

    try {
      const response = await fetch(`${API_BASE_URL}/chat/voice`, {
        method: "POST",
        body: formData,
        signal: controller.signal,
      });

      if (!response.ok) {
        const errorData = await response.json().catch(() => ({}));
        throw new Error(errorData.detail || `Server returned status ${response.status}`);
      }

      const data = await response.json();
      setResult({
        transcript: data.transcript,
        summary: data.summary,
        action_items: data.action_items,
        reply: data.reply,
        follow_up: data.follow_up,
        language: data.language,
      });
      const spoken = [data.reply, data.follow_up].filter(Boolean).join(" ");
      historyRef.current = [
        ...historyRef.current,
        { role: "user", content: data.transcript || "" },
        { role: "assistant", content: spoken },
      ].slice(-12);
      if (spoken) void speakSmart(spoken, data.language || "en-US");
    } catch (err) {
      console.error("Backend error:", err);
      const aborted = err instanceof DOMException && err.name === 'AbortError';
      setError(
        aborted
          ? "The server took too long to respond. It may be waking up, so please try again."
          : `Could not process the voice note: ${err instanceof Error ? err.message : 'unknown error'}`
      );
    } finally {
      clearTimeout(timeout);
      setLoading(false);
    }
  };

  return (
    <div className={`safe-screen min-h-dvh transition-colors duration-200 flex flex-col items-center ${darkMode ? 'dark bg-slate-950 text-slate-100' : 'bg-slate-100 text-slate-900'}`}>
      <div className="w-full max-w-2xl mx-auto my-auto space-y-3 min-[400px]:space-y-4 sm:space-y-6">
        <header className="w-full py-3 px-4 sm:py-4 sm:px-6 flex justify-between items-center gap-3 rounded-2xl border-2 border-slate-600 dark:border-slate-500 bg-white dark:bg-slate-900 shadow-sm">
          <div className="flex items-center gap-2 sm:gap-3 min-w-0">
            <span className="flex items-center justify-center w-9 h-9 rounded-xl bg-blue-600 text-white shadow-sm shrink-0" aria-hidden="true">
              <svg viewBox="0 0 24 24" className="w-5 h-5" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                <rect x="9" y="2" width="6" height="12" rx="3" fill="currentColor" stroke="none" />
                <path d="M5 11a7 7 0 0014 0M12 18v4M8 22h8" />
              </svg>
            </span>
            <h1 className="text-xl font-black tracking-tight text-slate-900 dark:text-white">Lima</h1>
            <span className="hidden min-[420px]:inline-block text-xs font-semibold px-2.5 py-0.5 rounded-full bg-blue-100 text-blue-900 dark:bg-blue-900/50 dark:text-blue-200 border-2 border-blue-600 dark:border-blue-400 whitespace-nowrap">
              Voice AI
            </span>
          </div>

          <div className="flex items-center gap-1.5 min-[400px]:gap-2 sm:gap-3 shrink-0">
            <button
              onClick={toggleTheme}
              className={iconButton}
              title="Toggle Theme"
              aria-label="Toggle Theme"
            >
              {darkMode ? (
                <svg className="w-5 h-5 text-yellow-400" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
                  <circle cx="12" cy="12" r="4" />
                  <path d="M12 2v2M12 20v2M4.93 4.93l1.41 1.41M17.66 17.66l1.41 1.41M2 12h2M20 12h2M4.93 19.07l1.41-1.41M17.66 6.34l1.41-1.41" />
                </svg>
              ) : (
                <svg className="w-5 h-5 fill-current text-slate-700" viewBox="0 0 24 24">
                  <path d="M12.3 2a10 10 0 00-1.9 20 10 10 0 0010.5-11 8.3 8.3 0 01-8.6-9z" />
                </svg>
              )}
            </button>

            <button
              onClick={() => setShowInstructions(true)}
              className={iconButton}
              title="Instructions"
              aria-label="Instructions"
            >
              <svg className="w-5 h-5 fill-none stroke-current stroke-2" viewBox="0 0 24 24">
                <circle cx="12" cy="12" r="10" />
                <line x1="12" y1="16" x2="12" y2="12" />
                <line x1="12" y1="8" x2="12.01" y2="8" />
              </svg>
            </button>

            <a
              href={REPO_URL}
              target="_blank"
              rel="noopener noreferrer"
              className={iconButton}
              title="View on GitHub"
              aria-label="View Lima on GitHub"
            >
              <svg className="w-5 h-5 fill-current" viewBox="0 0 24 24" aria-hidden="true">
                <path d="M12 .5C5.65.5.5 5.65.5 12c0 5.08 3.29 9.39 7.86 10.91.58.1.79-.25.79-.56v-2.17c-3.2.7-3.87-1.37-3.87-1.37-.52-1.33-1.28-1.69-1.28-1.69-1.04-.71.08-.7.08-.7 1.15.08 1.76 1.18 1.76 1.18 1.02 1.76 2.69 1.25 3.34.96.1-.74.4-1.25.72-1.54-2.55-.29-5.24-1.28-5.24-5.69 0-1.26.45-2.28 1.18-3.09-.12-.29-.51-1.46.11-3.05 0 0 .97-.31 3.17 1.18a11 11 0 015.78 0c2.2-1.49 3.17-1.18 3.17-1.18.62 1.59.23 2.76.11 3.05.74.81 1.18 1.83 1.18 3.09 0 4.42-2.7 5.39-5.27 5.68.41.36.78 1.06.78 2.14v3.17c0 .31.21.67.8.56A11.51 11.51 0 0023.5 12C23.5 5.65 18.35.5 12 .5z" />
              </svg>
            </a>
          </div>
        </header>

        <main className="text-center p-4 min-[400px]:p-5 sm:p-8 bg-white dark:bg-slate-900 rounded-2xl border-2 border-slate-600 dark:border-slate-500 shadow-md space-y-5 sm:space-y-6">
          <div>
            <h2 className="text-2xl sm:text-3xl text-balance leading-tight font-extrabold mb-2 text-slate-900 dark:text-white">
              Meet Lima • AI Voice Assistant
            </h2>
            <p className="text-sm sm:text-base font-medium text-slate-700 dark:text-slate-300">
              Ask a question or share a thought. Lima answers out loud and turns what you say into a clear summary and action items.
            </p>
          </div>

          <div className="flex flex-col items-center gap-3 py-2 sm:py-4">
            <div className="relative">
            {isRecording && (
              <span className="absolute inset-0 rounded-full bg-red-500/40 animate-ping pointer-events-none" aria-hidden="true" />
            )}
            <button
              onClick={handleRecordClick}
              disabled={loading || greeting || waitingMic}
              className={`record-btn w-32 h-32 sm:w-36 sm:h-36 rounded-full flex items-center justify-center font-bold text-white text-sm select-none transition-all transform active:scale-95 shadow-xl ${
                isRecording
                  ? 'bg-red-600 ring-4 ring-red-300 dark:ring-red-900 animate-pulse'
                  : greeting
                  ? 'bg-blue-500 ring-4 ring-blue-200 dark:ring-blue-900 animate-pulse cursor-not-allowed'
                  : loading
                  ? 'bg-slate-400 cursor-not-allowed'
                  : 'bg-blue-600 hover:bg-blue-700 dark:bg-blue-500 dark:hover:bg-blue-600'
              }`}
            >
              <span className="flex flex-col items-center gap-1.5">
                {isRecording ? (
                  <svg className="w-8 h-8" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
                    <rect x="6" y="6" width="12" height="12" rx="2" />
                  </svg>
                ) : loading ? (
                  <svg className="w-8 h-8 animate-spin" viewBox="0 0 24 24" fill="none" aria-hidden="true">
                    <circle cx="12" cy="12" r="9" stroke="currentColor" strokeWidth="3" opacity="0.3" />
                    <path d="M21 12a9 9 0 00-9-9" stroke="currentColor" strokeWidth="3" strokeLinecap="round" />
                  </svg>
                ) : (
                  <svg className="w-9 h-9" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                    <rect x="9" y="2" width="6" height="12" rx="3" fill="currentColor" stroke="none" />
                    <path d="M5 11a7 7 0 0014 0M12 18v4M8 22h8" />
                  </svg>
                )}
                <span className="text-xs sm:text-sm text-center px-2 leading-tight">
                  {greeting ? 'Lima is speaking...' : waitingMic ? 'Allow microphone' : loading ? 'Processing...' : isRecording ? 'Stop & Send' : 'Tap to talk'}
                </span>
              </span>
            </button>
            </div>
            {greeting && (
              <p className="text-sm font-medium text-blue-700 dark:text-blue-300">{GREETING}</p>
            )}
            {isRecording && (
              <p className="text-sm font-medium text-red-700 dark:text-red-300">
                Listening... speak now, then tap Stop &amp; Send.
              </p>
            )}
            {waitingMic && (
              <p className="text-sm font-medium text-blue-700 dark:text-blue-300">
                Tap "Allow" when your phone asks to use the microphone.
              </p>
            )}
            {loading && (
              <p className="text-xs text-slate-600 dark:text-slate-400">
                The first request can take up to a minute while the server wakes up.
              </p>
            )}
          </div>

          {error && (
            <div role="alert" className="text-left text-sm font-medium p-4 rounded-xl border-2 border-red-600 bg-red-50 text-red-900 dark:border-red-500 dark:bg-red-950/50 dark:text-red-200 break-words">
              {error}
            </div>
          )}

          {result && (
            <div className="text-left p-4 sm:p-6 bg-slate-50 dark:bg-slate-800/50 rounded-xl border-2 border-slate-600 dark:border-slate-500 space-y-4 text-slate-900 dark:text-slate-100 break-words [overflow-wrap:anywhere]">
              {result.reply && (
                <div>
                  <h3 className="text-xs uppercase tracking-wider font-bold text-slate-500 dark:text-slate-400 mb-1">Lima</h3>
                  <p className="text-base font-semibold leading-relaxed">{result.reply}</p>
                  {result.follow_up && (
                    <p className="mt-2 text-sm font-medium text-blue-700 dark:text-blue-300">{result.follow_up}</p>
                  )}
                  <button
                    onClick={listen}
                    className="mt-3 inline-flex items-center gap-2 text-sm font-semibold min-h-11 px-4 py-2 rounded-full border-2 border-blue-700 dark:border-blue-400 text-blue-800 dark:text-blue-200 hover:bg-blue-50 dark:hover:bg-blue-900/40 transition-colors"
                  >
                    <svg className="w-4 h-4" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                      <path d="M11 5L6 9H3v6h3l5 4V5z" fill="currentColor" />
                      <path d="M15.5 8.5a5 5 0 010 7M18.5 5.5a9 9 0 010 13" />
                    </svg>
                    Listen
                  </button>
                </div>
              )}

              {result.summary && (
                <div>
                  <h3 className="text-xs uppercase tracking-wider font-bold text-slate-500 dark:text-slate-400 mb-1">Summary</h3>
                  <p className="text-sm font-medium leading-relaxed">{result.summary}</p>
                </div>
              )}

              {result.action_items && result.action_items.length > 0 && (
                <div>
                  <h3 className="text-xs uppercase tracking-wider font-bold text-slate-500 dark:text-slate-400 mb-1">Action Items</h3>
                  <ul className="list-disc list-inside text-sm space-y-1 font-medium">
                    {result.action_items.map((item, idx) => (
                      <li key={idx}>{item}</li>
                    ))}
                  </ul>
                </div>
              )}

              {result.transcript && (
                <details className="text-xs text-slate-500 dark:text-slate-400 pt-2 border-t-2 border-slate-600 dark:border-slate-500">
                  <summary className="cursor-pointer py-2 font-semibold hover:text-slate-800 dark:hover:text-slate-200">
                    View raw transcript
                  </summary>
                  <p className="mt-2 italic bg-white dark:bg-slate-800 text-slate-800 dark:text-slate-200 p-3 rounded-lg border-2 border-slate-600 dark:border-slate-500">{result.transcript}</p>
                </details>
              )}
            </div>
          )}
        </main>
      </div>

      {showInstructions && (
        <div className="fixed inset-0 z-50 flex items-end sm:items-center justify-center bg-black/60 backdrop-blur-xs p-0 sm:p-4" onClick={() => setShowInstructions(false)}>
          <div role="dialog" aria-modal="true" aria-label="How to use Lima" className="sheet-up bg-white dark:bg-slate-900 text-slate-900 dark:text-white rounded-t-3xl sm:rounded-2xl p-5 sm:p-6 pb-[max(1.25rem,env(safe-area-inset-bottom))] max-w-md w-full max-h-[90dvh] overflow-y-auto shadow-2xl border-2 border-slate-600 dark:border-slate-500" onClick={(e) => e.stopPropagation()}>
            <h3 className="text-xl font-bold mb-3">How to use Lima</h3>
            <ul className="list-disc list-inside text-sm text-slate-700 dark:text-slate-300 space-y-2.5 mb-6 leading-relaxed">
              <li>Tap the microphone button to start recording your voice note.</li>
              <li>Speak clearly about your project, tasks, or ideas, then tap stop.</li>
              <li>Lima listens, answers you out loud, and adds a short summary and action items.</li>
            </ul>
            <button
              onClick={() => setShowInstructions(false)}
              className="w-full min-h-12 py-3 bg-blue-600 hover:bg-blue-700 text-white text-sm font-semibold rounded-xl transition-colors shadow-md"
            >
              Got it
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
